/**
 * Enhanced Industry Template System
 * Multiple styles, color palettes, and typography options per industry
 * Ensures every website is unique and industry-appropriate
 */

export interface IndustryStyle {
  id: string
  name: string
  description: string
  layout: 'editorial' | 'minimal' | 'bold' | 'elegant' | 'playful' | 'industrial' | 'modern' | 'classic'
  cardStyle: 'rounded' | 'sharp' | 'pill' | 'organic' | 'glass' | 'elevated'
  headerStyle: 'transparent' | 'solid' | 'gradient' | 'split' | 'minimal'
  sectionStyle: 'alternating' | 'uniform' | 'dynamic' | 'layered'
  animationStyle: 'subtle' | 'smooth' | 'dramatic' | 'playful'
}

export interface ColorPalette {
  id: string
  name: string
  primary: string
  secondary: string
  accent: string
  bg: string
  text: string
  mood: string
}

export interface TypographyOption {
  id: string
  name: string
  heading: string
  body: string
  description: string
  weight: 'light' | 'regular' | 'medium' | 'bold'
  spacing: 'tight' | 'normal' | 'relaxed'
}

